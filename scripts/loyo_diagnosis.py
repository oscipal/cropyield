"""Step 1 of the LOYO diagnosis: where does the ConvLSTM's held-out-year error come from, and what in the data could
cause it? Read-only: uses the val predictions of an existing run and the data, trains nothing.

    python scripts/loyo_diagnosis.py                      # -> docs/loyo_diagnosis.md
    python scripts/loyo_diagnosis.py --config convlstm_s2

Val only (the test years 2017 Europe / 2021 South America and World are not looked at, also not in the label
statistics). Splits: europe/loyo/all (val 2018), south_america/loyo/all and world/loyo/all (val 2022).

CLAUDE.md: no Swiss data values. Everything that shows yield levels or yield distributions (t/ha, z-scores of year
means, label variability) is computed for Argentina, Brazil, Uruguay and Germany only; for Switzerland only counts
and model scores (R2, error shares) are reported.

Sections:
  A  error decomposition of the val field means per country x crop: level (bias), scale, scatter (Murphy 1988)
  B  year structure of the labels: years per country x crop, between-year share of the field-mean variance, where the
     val year lies relative to the training years
  C  does the predicted year level follow the actual one (predicted vs actual anomaly of the val year)?
  D  Sentinel-2 coverage of the season, val year vs training years
  E  sowing-date reliability (seeding_date_type)
  F  val fields whose physical field is in train ("seen") vs not ("unseen")
  G  within-field error and label variability by distance to the field edge
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.config import REPO_ROOT, load_paths  # noqa: E402
from src.splits import load_split  # noqa: E402

SPLITS = ["europe/loyo/all", "south_america/loyo/all", "world/loyo/all"]
TEST_YEARS = {"Germany": "2017", "Switzerland": "2017", "Argentina": "2021", "Brazil": "2021", "Uruguay": "2021"}
NO_VALUES = {"Switzerland"}            # CLAUDE.md: counts and model scores only
MIN_FIELDS = 5


def fmt(x, nd=2):
    return "–" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{nd}f}"


def table(df: pd.DataFrame) -> list[str]:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(fmt(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return out + [""]


def field_means(preds: pd.DataFrame) -> pd.DataFrame:
    return preds.groupby("field", sort=False).agg(country=("country", "first"), crop=("crop", "first"),
                                                  year=("year", "first"), obs=("target", "mean"),
                                                  pred=("pred", "mean"), n_px=("target", "size")).reset_index()


def decompose(o: np.ndarray, p: np.ndarray) -> dict:
    """MSE = bias^2 + (sd_p - r sd_o)^2 + (1 - r^2) sd_o^2 (Murphy 1988); shares of the MSE, R2, corr, and the R2
    the same predictions would have with the level corrected (bias removed)."""
    mse = np.mean((p - o) ** 2)
    so, sp = o.std(), p.std()
    r = np.corrcoef(o, p)[0, 1] if so > 0 and sp > 0 else np.nan
    bias = p.mean() - o.mean()
    level, scale, scatter = bias ** 2, (sp - r * so) ** 2, (1 - r ** 2) * so ** 2
    r2 = 1 - mse / so ** 2
    return {"n": len(o), "r2": r2, "r2_level_fixed": 1 - (mse - level) / so ** 2, "corr": r, "bias": bias,
            "level": level / mse, "scale": scale / mse, "scatter": scatter / mse}


def edge_dist(g: pd.DataFrame) -> np.ndarray:
    """Distance (m) of each pixel to the nearest non-labelled cell of its field raster (10 m pixels)."""
    from scipy.ndimage import distance_transform_edt
    r, c = g["row"].to_numpy() - g["row"].min() + 1, g["col"].to_numpy() - g["col"].min() + 1
    m = np.zeros((r.max() + 2, c.max() + 2), bool)
    m[r, c] = True
    return distance_transform_edt(m)[r, c] * 10.0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="convlstm_s2")
    ap.add_argument("--out", default="docs/loyo_diagnosis.md")
    a = ap.parse_args()
    paths = load_paths()
    work = paths["work_dir"]
    runs = work / "lstm" / "runs" / a.config
    fields = pd.read_parquet(work / "fields.parquet").set_index("field")
    fields["year"] = fields["year"].astype(str)
    L = [f"# LOYO diagnosis: where the held-out-year error comes from", "",
         f"Generated by `scripts/loyo_diagnosis.py` (step 1 of the systematic approach, 2026-10-25). Model: "
         f"`{a.config}` (5-member ensemble), **val** predictions of the pooled LOYO splits; the test years are not "
         f"looked at, also not in the label statistics. Read-only: nothing was trained.", "",
         "Data rule: yield levels and distributions are shown for Argentina, Brazil, Uruguay and Germany only; "
         "Switzerland gets counts and model scores only.", ""]

    # ------------------------------------------------------------------ A, C, F, G per split
    A_rows, C_rows, F_rows, G_parts = [], [], [], []
    for split in SPLITS:
        scope, method, crop = split.split("/")
        s = load_split(paths["split_suite"], scope, method, crop)
        val_year = s["attrs"]["val_years"][0] if "val_years" in s["attrs"] else "?"
        preds = pd.read_parquet(runs / split.replace("/", "__") / "preds_val.parquet",
                                columns=["field", "country", "crop", "year", "row", "col", "target", "pred"])
        fm = field_means(preds)
        train = fields.loc[s["train_fields"]]
        phys_train = set(train["physical_field"])
        fm["seen"] = fields.loc[fm["field"], "physical_field"].isin(phys_train).to_numpy()
        for (cty, crp), g in fm.groupby(["country", "crop"]):
            if len(g) < MIN_FIELDS:
                continue
            d = decompose(g["obs"].to_numpy(), g["pred"].to_numpy())
            row = {"split": split, "val year": val_year, "country": cty, "crop": crp, "fields": d["n"],
                   "field R2": d["r2"], "R2 if level fixed": d["r2_level_fixed"], "corr": d["corr"],
                   "level share": d["level"], "scale share": d["scale"], "scatter share": d["scatter"],
                   "bias t/ha": np.nan if cty in NO_VALUES else d["bias"]}
            A_rows.append(row)
            if cty not in NO_VALUES:
                tr = train[(train["country"] == cty) & (train["crop"] == crp)]
                tr_mean = tr["yield_mean"].mean()
                tr_years = tr.groupby("year")["yield_mean"].mean()
                C_rows.append({"split": split, "country": cty, "crop": crp, "train years": len(tr_years),
                               "actual anomaly t/ha": g["obs"].mean() - tr_mean,
                               "predicted anomaly t/ha": g["pred"].mean() - tr_mean,
                               "train year-mean range t/ha": tr_years.max() - tr_years.min() if len(tr_years) else np.nan})
            for seen, h in g.groupby("seen"):
                F_rows.append({"split": split, "country": cty, "crop": crp, "seen": seen, "n": len(h),
                               "abs err": np.abs(h["pred"] - h["obs"]).to_numpy(),
                               "abs err, level removed": np.abs((h["pred"] - h["obs"]) - (g["pred"] - g["obs"]).mean()).to_numpy()})
        if split != "world/loyo/all":           # world val = union of the two others' 2022 + Europe 2022
            px = preds[~preds["country"].isin(NO_VALUES)].copy()
            px["edge_m"] = np.concatenate([edge_dist(g) for _, g in px.groupby("field", sort=False)])
            px = px.merge(fm[["field", "obs", "pred"]].rename(columns={"obs": "fobs", "pred": "fpred"}), on="field")
            px["dev_obs"], px["dev_pred"] = px["target"] - px["fobs"], px["pred"] - px["fpred"]
            G_parts.append(px[["country", "crop", "edge_m", "dev_obs", "dev_pred"]])

    A = pd.DataFrame(A_rows)
    L += ["## A. Error decomposition of the val field means", "",
          "Per country × crop subset (≥ 5 val fields), field-level: mean-squared error split into **level** (the "
          "whole held-out year predicted too high / low: bias²), **scale** (predictions too flat or too spread: "
          "(sd_pred − r·sd_obs)²) and **scatter** (fields ranked wrongly: (1 − r²)·sd_obs²), as shares of the MSE "
          "(Murphy 1988, *Mon. Weather Rev.* 116). *R² if level fixed* = the R² of the same predictions with the "
          "subset's bias removed: an upper bound of what correcting the year level alone would give.", ""]
    L += table(A.round(3))
    med = A[["field R2", "R2 if level fixed", "level share", "scale share", "scatter share", "corr"]].median()
    neg = A[A["field R2"] < 0]
    L += [f"Median over {len(A)} subsets: field R² {med['field R2']:.2f}, with the level fixed "
          f"{med['R2 if level fixed']:.2f}; error shares level {med['level share']:.2f}, scale "
          f"{med['scale share']:.2f}, scatter {med['scatter share']:.2f}; correlation {med['corr']:.2f}. "
          f"Of the {len(neg)} subsets with negative R², {int((neg['level share'] > 0.5).sum())} have more than half "
          f"of their error in the level.", ""]

    # ------------------------------------------------------------------ B. year structure of the labels
    fy = fields[~fields["country"].isin(NO_VALUES)].copy()
    fy = fy[fy["year"] != fy["country"].map(TEST_YEARS)]                 # test years left out
    B_rows = []
    for (cty, crp), g in fy.groupby(["country", "crop"]):
        ym = g.groupby("year")["yield_mean"].agg(["mean", "size"])
        tot = g["yield_mean"].var()
        between = np.average((ym["mean"] - g["yield_mean"].mean()) ** 2, weights=ym["size"]) if len(ym) > 1 else np.nan
        B_rows.append({"country": cty, "crop": crp, "years (no test year)": len(ym),
                       "field-years": len(g), "min fields / year": int(ym["size"].min()),
                       "between-year share of variance": between / tot if tot > 0 else np.nan,
                       "range of year means t/ha": ym["mean"].max() - ym["mean"].min(),
                       "within-year sd t/ha": float(np.sqrt(np.average(g.groupby("year")["yield_mean"].var().fillna(0),
                                                                       weights=ym["size"])))})
    B = pd.DataFrame(B_rows)
    sw = fields[fields["country"].isin(NO_VALUES)]
    sw = sw[sw["year"] != sw["country"].map(TEST_YEARS)]
    swc = sw.groupby("crop").agg(years=("year", "nunique"), field_years=("yield_mean", "size")).reset_index()
    L += ["## B. Year structure of the labels (test years left out)", "",
          "Field-mean yields per country × crop. *Between-year share* = part of the variance of field-mean yields "
          "explained by the year (year means weighted by field count). This is what a LOYO model has to predict "
          "for an unseen year, from few years.", ""]
    L += table(B.round(2))
    L += ["Switzerland (counts only): " + ", ".join(f"{r.crop} {r.years} years / {r.field_years} field-years"
                                                     for r in swc.itertuples()) + ".", ""]

    # ------------------------------------------------------------------ C. year level tracking
    C = pd.DataFrame(C_rows)
    agree = np.sign(C["actual anomaly t/ha"]) == np.sign(C["predicted anomaly t/ha"])
    L += ["## C. Does the predicted year level follow the actual one?", "",
          "Val year mean minus the training mean of the same country × crop: actual (labels) vs predicted (model). "
          "If the model captured the year effect, the two would agree in sign and size.", ""]
    L += table(C.round(2))
    corr = np.corrcoef(C["actual anomaly t/ha"], C["predicted anomaly t/ha"])[0, 1] if len(C) > 2 else np.nan
    slope = np.polyfit(C["actual anomaly t/ha"], C["predicted anomaly t/ha"], 1)[0] if len(C) > 2 else np.nan
    L += [f"Sign agrees in {int(agree.sum())} / {len(C)} subsets; correlation of actual and predicted anomaly "
          f"{fmt(corr)}, slope {fmt(slope)} (1 = full year effect captured, 0 = none). Few points, read loosely.", ""]

    # ------------------------------------------------------------------ D. S2 coverage
    from src.loader import load, seasons
    D_rows = []
    for split in ("europe/loyo/all", "south_america/loyo/all"):
        for role in ("train", "val"):
            d = load(split, role=role, features=["observed"], grid="10d", align="sowing", pixels_per_field=50,
                     verbose=False)
            obs = d.dyn[..., 0].astype(np.float32)                         # (pixels, 36 steps after sowing)
            s = seasons().reindex(d.meta["field"].to_numpy())
            n_season = np.clip(((s["harvest_day"] - s["sow_day"]).fillna(360).to_numpy() // 10).astype(int), 1,
                               obs.shape[1])
            in_season = np.arange(obs.shape[1])[None, :] < n_season[:, None]
            frac = (obs * in_season).sum(1) / in_season.sum(1)
            t = pd.DataFrame({"country": d.meta["country"].to_numpy(), "crop": d.meta["crop"].to_numpy(),
                              "field": d.meta["field"].to_numpy(), "frac": frac})
            t = t.groupby(["country", "crop", "field"])["frac"].median().groupby(["country", "crop"]).median()
            for (cty, crp), v in t.items():
                D_rows.append({"split": split, "country": cty, "crop": crp, "set": role, "clear share": v})
    D = pd.DataFrame(D_rows).pivot_table(index=["split", "country", "crop"], columns="set",
                                         values="clear share").reset_index()
    D["val − train"] = D["val"] - D["train"]
    L += ["## D. Sentinel-2 coverage of the season", "",
          "Share of the 10-day windows between sowing and harvest with a clear observation (median pixel of the "
          "median field; 50 pixels per field), training years vs the val year.", ""]
    L += table(D.round(2))

    # ------------------------------------------------------------------ E. sowing dates
    s = seasons().join(fields[["country", "crop"]], how="inner")
    E = s.groupby(["country", "crop"])["seeding_date_type"].value_counts().unstack(fill_value=0).reset_index()
    E.columns.name = None
    L += ["## E. Sowing-date reliability", "", "`seeding_date_type` from the metadata, field-years (all years).", ""]
    L += table(E)

    # ------------------------------------------------------------------ F. seen vs unseen physical fields
    F = pd.DataFrame(F_rows)
    Fs = F.groupby(["split", "seen"]).agg(n=("n", "sum"),
                                          mae=("abs err", lambda x: np.median(np.concatenate(list(x)))),
                                          mae_l=("abs err, level removed",
                                                 lambda x: np.median(np.concatenate(list(x))))).reset_index()
    Fs["seen"] = Fs["seen"].map({True: "physical field in train", False: "new field"})
    Fs = Fs.rename(columns={"mae": "median abs error t/ha", "mae_l": "same, subset level removed"})
    L += ["## F. Seen vs new fields", "",
          "Val fields whose physical field (same land, other year) is in the training set vs fields never seen in "
          "training. The target scenario is new fields in a new year. All countries pooled (errors only).", ""]
    L += table(Fs.round(2))

    # ------------------------------------------------------------------ G. edge distance
    G = pd.concat(G_parts, ignore_index=True)
    G["band"] = pd.cut(G["edge_m"], [0, 10.5, 20.5, 30.5, 50.5, 1e9], labels=["10 m (edge)", "20 m", "30 m",
                                                                             "40–50 m", "> 50 m"])
    Gt = G.groupby("band", observed=True).agg(
        pixels=("dev_obs", "size"), label_sd=("dev_obs", "std"),
        error_rmse=("dev_obs", lambda x: float(np.sqrt(np.mean((G.loc[x.index, "dev_pred"] - x) ** 2)))),
        corr=("dev_obs", lambda x: float(np.corrcoef(x, G.loc[x.index, "dev_pred"])[0, 1]))).reset_index()
    Gt = Gt.rename(columns={"label_sd": "sd of label deviation t/ha", "error_rmse": "within-field RMSE t/ha",
                            "corr": "within-field corr"})
    L += ["## G. Within-field error by distance to the field edge", "",
          "Pixel deviation from its field mean, labels vs predictions (val, Europe 2018 + South America 2022, "
          "Switzerland left out). Edge pixels of yield-monitor maps are known to be noisy (headlands, partial "
          "swaths; Perich et al. 2023 and Vallentin et al. 2022 use a 20 m inward buffer).", ""]
    L += table(Gt.round(3))

    out = REPO_ROOT / a.out
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out} ({len(A)} subsets in A)")


if __name__ == "__main__":
    main()
