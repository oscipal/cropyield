"""How a model's errors depend on how patchy a field's yield map is (world variants; user, 2026-10-28). Reads the
run's predictions only, trains nothing.

    python scripts/LSTM/21_patchiness.py --config wv_base                  # -> docs/patchiness_wv_base.md
    python scripts/LSTM/21_patchiness.py --config wv_base --split world/loyo/all --roles val test

Patchiness of a field-year, from its labelled pixels (meta.parquet row / col; outline = the labelled area with its
holes filled):
    hole_share      share of the outline without yield (holes in the yield map)
    holes_per_ha    number of holes (4-connected gaps inside the outline) per ha of outline
    small_holes     share of the holes that are < 25 pixels (0.25 ha), i.e. gaps rather than obstacles
    edge_share      share of the labelled pixels within 20 m of the outline
    gap_share       share of the labelled pixels within 20 m of a hole (but not of the outline)
    area_ha         labelled area

Errors (ensemble prediction `pred`; also the member mean of the field errors):
    field_abs_rel   |mean prediction - mean target| / mean target of the field-year (%), comparable across crops
    within_r        Pearson r between pixel prediction and target inside the field-year (within-field pattern)
    pixel_rmse_rel  pixel RMSE / mean target (%)
and per pixel: absolute error by distance to the nearest edge / hole.

Summaries: field-years in quintiles of each patchiness measure (pooled over country x crop); per country x crop
subset (>= 10 field-years) the Spearman rank correlation of the measure with field_abs_rel and within_r, median over
subsets. Only relative errors and correlations are written, no yield levels; the per-subset tables leave
Switzerland out (CLAUDE.md), the pooled bins include it.
"""
from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.ndimage import binary_fill_holes, distance_transform_edt, label
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from src.config import REPO_ROOT, load_paths  # noqa: E402

PX_M, BUF_M, SMALL_HOLE = 10.0, 20.0, 25
MEASURES = ["hole_share", "holes_per_ha", "small_holes", "edge_share", "gap_share", "area_ha"]
HIDDEN = ("Switzerland",)


def field_patchiness(rr: np.ndarray, cc: np.ndarray) -> tuple[dict, np.ndarray, np.ndarray]:
    """Measures of one field-year and, per labelled pixel, distance (m) to the outline and to the nearest hole."""
    r0, c0 = rr.min() - 1, cc.min() - 1
    m = np.zeros((rr.max() - r0 + 2, cc.max() - c0 + 2), bool)
    m[rr - r0, cc - c0] = True
    filled = binary_fill_holes(m)
    holes = filled & ~m
    lab, n = label(holes)
    sizes = np.bincount(lab.ravel())[1:] if n else np.zeros(0, int)
    d_out = distance_transform_edt(filled)[rr - r0, cc - c0] * PX_M
    d_hole = (distance_transform_edt(~holes)[rr - r0, cc - c0] * PX_M) if n else np.full(len(rr), np.inf)
    area = filled.sum() * PX_M ** 2 / 1e4
    return ({"hole_share": holes.sum() / filled.sum(), "holes_per_ha": n / area,
             "small_holes": float((sizes < SMALL_HOLE).mean()) if n else np.nan,
             "edge_share": float((d_out <= BUF_M).mean()), "gap_share": float(((d_hole <= BUF_M) & (d_out > BUF_M)).mean()),
             "area_ha": m.sum() * PX_M ** 2 / 1e4}, d_out, d_hole)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="wv_base")
    ap.add_argument("--split", default="world/loyo/all")
    ap.add_argument("--roles", nargs="+", default=["val", "test"])
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    work = load_paths()["work_dir"]
    run = work / "lstm" / "runs" / args.config / args.split.replace("/", "__")
    meta = pd.read_parquet(work / "lstm" / "data" / "meta.parquet", columns=["field", "row", "col"])
    out = Path(args.out) if args.out else REPO_ROOT / "docs" / f"patchiness_{args.config}.md"

    L = [f"# Error vs patchiness of the yield map: `{args.config}`, `{args.split}`", "",
         f"Generated by `scripts/LSTM/21_patchiness.py` on {date.today().isoformat()} from the run's predictions "
         f"(nothing trained). Ensemble prediction of all members. Relative errors and correlations only "
         f"(no yield levels); per-subset tables without Switzerland, pooled bins with it (CLAUDE.md).", "",
         "Measures per field-year: **hole_share** = share of the field outline (labelled area with holes filled) "
         "without yield; **holes_per_ha** = gaps inside the outline per ha; **small_holes** = share of the holes "
         f"< {SMALL_HOLE} pixels (0.25 ha); **edge_share** = share of the pixels within {BUF_M:.0f} m of the outline; "
         f"**gap_share** = share of the pixels within {BUF_M:.0f} m of a hole but not of the outline; **area_ha**. "
         "Errors: **field_abs_rel** = |mean prediction − mean target| / mean target of the field-year (%); "
         "**within_r** = Pearson r of pixel prediction vs target inside the field-year; **pixel_rmse_rel** = pixel "
         "RMSE / mean target (%).", ""]
    for role in args.roles:
        p = pd.read_parquet(run / f"preds_{role}.parquet")
        # patchiness from all labelled pixels of each field-year (not only the predicted ones)
        fields = p["field"].unique()
        mm = meta[meta["field"].isin(fields)]
        recs, dist = [], []
        for f, g in mm.groupby("field", sort=False, observed=True):
            meas, d_out, d_hole = field_patchiness(g["row"].to_numpy(np.int64), g["col"].to_numpy(np.int64))
            recs.append({"field": f, **meas})
            dist.append(pd.DataFrame({"field": f, "row": g["row"].to_numpy(), "col": g["col"].to_numpy(),
                                      "d_out": d_out, "d_hole": d_hole}))
        pm = pd.DataFrame(recs).set_index("field")
        dist = pd.concat(dist)
        q = p.merge(dist, on=["field", "row", "col"], how="left")
        fe = q.groupby("field").apply(lambda g: pd.Series({
            "country": g["country"].iloc[0], "crop": g["crop"].iloc[0],
            "field_abs_rel": 100 * abs(g["pred"].mean() - g["target"].mean()) / g["target"].mean(),
            "within_r": np.corrcoef(g["pred"], g["target"])[0, 1] if len(g) > 2 and g["pred"].std() > 0 else np.nan,
            "pixel_rmse_rel": 100 * np.sqrt(((g["pred"] - g["target"]) ** 2).mean()) / g["target"].mean()}),
            include_groups=False).join(pm)
        L += [f"## {role} ({len(fe)} field-years)", ""]

        L += ["### Pooled: errors by quintile of each measure", "",
              "| measure | quintile | range | field-years | median field_abs_rel % | median within_r | median pixel_rmse_rel % |",
              "|---|---|---|---|---|---|---|"]
        for m in MEASURES:
            v = fe[m].dropna()
            if v.nunique() < 5:
                continue
            bins = pd.qcut(v.rank(method="first"), 5, labels=False)
            for k in range(5):
                s = fe.loc[bins[bins == k].index]
                L.append(f"| {m} | {k + 1} | {s[m].min():.3g}–{s[m].max():.3g} | {len(s)} | "
                         f"{s['field_abs_rel'].median():.1f} | {s['within_r'].median():.2f} | "
                         f"{s['pixel_rmse_rel'].median():.1f} |")
        L.append("")

        sub = fe[~fe["country"].isin(HIDDEN)]
        L += ["### Per country × crop: Spearman ρ of each measure with the errors (subsets with ≥ 10 field-years)", "",
              "Positive ρ with field_abs_rel = patchier fields have larger field errors; negative ρ with within_r = "
              "patchier fields have a worse within-field pattern.", "",
              "| measure | subsets | median ρ (field_abs_rel) | median ρ (within_r) | median ρ (pixel_rmse_rel) |",
              "|---|---|---|---|---|"]
        per = []
        for (c, cr), g in sub.groupby(["country", "crop"]):
            if len(g) < 10:
                continue
            for m in MEASURES:
                if g[m].nunique() < 3:
                    continue
                per.append({"country": c, "crop": cr, "measure": m, "n": len(g),
                            **{e: spearmanr(g[m], g[e], nan_policy="omit")[0]
                               for e in ("field_abs_rel", "within_r", "pixel_rmse_rel")}})
        per = pd.DataFrame(per)
        for m in MEASURES:
            s = per[per["measure"] == m] if len(per) else per
            if len(s):
                L.append(f"| {m} | {len(s)} | {s['field_abs_rel'].median():+.2f} | {s['within_r'].median():+.2f} | "
                         f"{s['pixel_rmse_rel'].median():+.2f} |")
        L.append("")
        if len(per):
            L += ["| country | crop | field-years | " + " | ".join(f"ρ {m} vs field_abs_rel" for m in MEASURES) + " |",
                  "|---|---|---|" + "---|" * len(MEASURES)]
            for (c, cr), g in per.groupby(["country", "crop"]):
                r = g.set_index("measure")["field_abs_rel"]
                L.append(f"| {c} | {cr} | {g['n'].iloc[0]} | " + " | ".join(
                    f"{r[m]:+.2f}" if m in r else "–" for m in MEASURES) + " |")
            L.append("")

        L += ["### Pixel error by distance to the edge / to a hole (pooled, relative to the field mean target)", "",
              "| distance (m) | to the outline: pixels | median abs. error % | to a hole (> 20 m from the outline): pixels | median abs. error % |",
              "|---|---|---|---|---|"]
        tm = q.groupby("field")["target"].transform("mean")
        q["abs_rel"] = 100 * (q["pred"] - q["target"]).abs() / tm
        edges = [0, 10, 20, 30, 50, 100, np.inf]
        names = ["10", "20", "30", "40–50", "60–100", "> 100"]
        bo = pd.cut(q["d_out"], edges, right=True, labels=names)
        inner = q["d_out"] > BUF_M
        bh = pd.cut(q.loc[inner, "d_hole"], edges, right=True, labels=names)
        for nm in names:
            a = q.loc[bo == nm, "abs_rel"]
            h = q.loc[inner].loc[bh == nm, "abs_rel"]
            L.append(f"| {nm} | {len(a):,} | {a.median():.1f} | {len(h):,} | {h.median():.1f} |" if len(h)
                     else f"| {nm} | {len(a):,} | {a.median():.1f} | 0 | – |")
        L.append("")
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
