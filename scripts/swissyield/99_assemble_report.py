"""Join report/*.md sections into <work_dir>/swissyield/profile.md (+ figure index)."""
from __future__ import annotations

from swiss_lib import FIGURES, OUT, REPORT


def main() -> None:
    parts = ["# SwissYield profile (generated by scripts/swissyield; run_all.sh)\n"]
    for p in sorted(REPORT.glob("*.md")):
        parts.append(p.read_text())
    parts.append("\n# Figures\n\n" + "\n".join(f"- `figures/{p.name}`" for p in sorted(FIGURES.glob("*.png"))))
    (OUT / "profile.md").write_text("\n\n".join(parts))
    print("wrote", OUT / "profile.md")


if __name__ == "__main__":
    main()
