"""Write docs/features.md from the feature registry (src/features.py) and the data: what every loader feature is,
its unit, source, known issues, and how complete it is per country.

    python scripts/features_doc.py

Coverage and medians come from PER_FIELD random pixels of every field-year (seed 0), loaded with src/loader.py.
Medians are shown for the YieldSAT countries only; for Switzerland only coverage shares (CLAUDE.md: Swiss values
are not inspected).
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import features as F  # noqa: E402
from src import soil  # noqa: E402
from src.config import REPO_ROOT  # noqa: E402
from src.loader import GRIDS, load  # noqa: E402

PER_FIELD = 200
PRIVATE = ("Switzerland",)
COUNTRIES = ["Germany", "Switzerland", "Argentina", "Brazil", "Uruguay"]
SHOWN = [c for c in COUNTRIES if c not in PRIVATE]
ABBR = {"Germany": "DE", "Switzerland": "CH", "Argentina": "AR", "Brazil": "BR", "Uruguay": "UY"}


def fmt(v: float) -> str:
    if not np.isfinite(v):
        return "–"
    return f"{v:,.0f}" if abs(v) >= 1000 else f"{v:.3g}"


def stats(d, arr: np.ndarray, names: list[str]) -> pd.DataFrame:
    """Per feature and country: share present (not NaN) and median (YieldSAT countries only)."""
    country = d.meta["country"].to_numpy()
    out = {}
    for j, n in enumerate(names):
        r = {}
        for c in COUNTRIES:
            v = arr[country == c][..., j].astype(np.float32).ravel()
            ok = np.isfinite(v)
            r[("present", c)] = ok.mean() if v.size else np.nan
            r[("median", c)] = np.median(v[ok]) if ok.any() and c not in PRIVATE else np.nan
        out[n] = r
    return pd.DataFrame(out).T


def table(rows: list[tuple[str, str, str, str | None]], st: pd.DataFrame) -> list[str]:
    """rows: (feature key in st, label, unit, meaning, default-flag or None)."""
    has_def = any(r[4] is not None for r in rows)
    head = ["feature", "unit", "meaning"] + (["default"] if has_def else []) \
        + [f"present {ABBR[c]}" for c in COUNTRIES] + [f"median {ABBR[c]}" for c in SHOWN]
    n_text = 4 if has_def else 3
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * n_text + "---:|" * (len(head) - n_text)]
    for key, label, unit, meaning, default in rows:
        cells = [f"`{label}`", unit, meaning] + ([default] if has_def else [])
        cells += [f"{st.at[key, ('present', c)]:.0%}" for c in COUNTRIES]
        cells += [fmt(st.at[key, ("median", c)]) for c in SHOWN]
        out.append("| " + " | ".join(cells) + " |")
    return out + [""]


def main() -> None:
    dyn_specs = ["s2", "indices", "observed", "weather:all"]
    by_grid = {g: load(features=dyn_specs, grid=g, pixels_per_field=PER_FIELD, dtype=np.float32, verbose=False)
               for g in GRIDS}
    d = by_grid["10d"]
    dyn = stats(d, d.dyn, d.dyn_names)
    s = load(features=["terrain", "coords"] + [f"soil:{p}@0-30cm" for p in soil.PROPS], grid="30d",
             pixels_per_field=PER_FIELD, verbose=False)
    sta = stats(s, s.static, s.static_names)

    L = ["# Input features", "",
         "Generated by `scripts/features_doc.py` from the registry `src/features.py` and the data. Load the "
         "features with `src/loader.py`:", "", "```python", "from src.loader import load, fit_scaler, YieldDataset",
         'd = load("world/loyo/all", role="train", grid="10d",',
         '         features=["s2", "indices", "observed", "weather", "terrain", "soil:0-30cm", "crop", "country"])',
         "ds = YieldDataset(d, fit_scaler(d))   # torch Dataset, z-scored, NaN -> 0", "```", "",
         "Feature specs are `group` or `group:argument` (e.g. `s2:B04,B08`, `weather:tmean_c,prec_mm`, "
         "`weather:all`, `terrain:slope`, `soil:clay,soc@0-60cm`). `d.dyn` is (pixels, steps, features), "
         "`d.static` (pixels, features), both in the units below, NaN = missing.", "",
         "## Time grids", "",
         "`30d`, `15d`, `10d`: windows of 30 / 15 / 10 days from day 210 to day 720, day 0 = 1 January of the year "
         "before the harvest year (`src/season.py`); `d.days` holds the first day of every window. The delivered "
         "24-step YieldSAT cube has no data before day 210; our 30-day grid equals its steps 7–23 except 410 "
         "Brazilian pixels where the delivered cube keeps SCL-0 pixels.", "",
         "| grid | steps | windows with a clear observation (all pixels and steps) |", "|---|---:|---:|"]
    for g, dg in by_grid.items():
        L.append(f"| `{g}` | {dg.dyn.shape[1]} | {dg.dyn[..., dg.dyn_names.index('observed')].mean():.0%} |")
    L += ["", f"Coverage (`present`) = share of values that are not NaN in {PER_FIELD} random pixels of every "
          "field-year; for dynamic features over all steps of the 10-day grid, so it includes windows outside the "
          "season. Medians are not shown for Switzerland (Swiss values are not inspected).", ""]

    for g in F.DYNAMIC_GROUPS + F.STATIC_GROUPS:
        src, what, issues = F.GROUP_DOCS[g]
        L += [f"## `{g}`" + (" (per time step)" if g in F.DYNAMIC_GROUPS else " (per pixel)"), "",
              f"- **What:** {what}", f"- **Source:** {src}", f"- **Known issues:** {issues}", ""]
        if g == "s2":
            L += table([(b, b, "reflectance", "", None) for b in F.S2_BANDS], dyn)
        elif g == "indices":
            L += table([(i, i, "-1..1", F.INDEX_DOCS[i], None) for i in F.INDICES], dyn)
        elif g == "observed":
            L += table([("observed", "observed", "0/1", "clear S2 observation", None)], dyn)
        elif g == "weather":
            L += table([(w, w, F.WEATHER_UNITS[w], F.WEATHER_DOCS[w], "yes" if w in F.WEATHER_DEFAULT else "no")
                        for w in F.WEATHER_UNITS], dyn)
        elif g == "terrain":
            L += table([(t, t, F.TERRAIN_UNITS[t], F.TERRAIN_DOCS[t], None) for t in F.TERRAIN_UNITS], sta)
        elif g == "soil":
            L += ["Depth spec: any range within 0–200 cm, averaged over the standard layers "
                  + ", ".join(f"{a}–{b}" for a, b in soil.LAYERS) + " cm weighted by thickness. Shown: 0–30 cm.", ""]
            L += table([(f"soil_{p}_0-30cm", p, u, m, None) for p, (_, u, m) in soil.PROPS.items()], sta)
        elif g == "coords":
            L += table([(c, c, "as delivered", "", None) for c in F.COORDS], sta)
    out = REPO_ROOT / "docs" / "features.md"
    out.write_text("\n".join(L))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
